"""Check the N6 memory map in models.json and write the firmware header it implies.

    python tools/models_layout.py            check, print the map, write xl_models.h
    python tools/models_layout.py --check    check only (exit 1 on a problem)

firmware-n6/src/application/translator/models.json lists every region of the 128 MB octal NOR
(boot loader, application, each model blob) and of the 32 MB PSRAM. Each flash blob has a slot
(address and size); its file must fit. flash.py --models programs the blobs that have a file.
The NPU networks (ASR, flow, vocoder) have their addresses compiled in by ST Edge AI: their
memory-pool files must match this map (model-tools/mpool_edit.py writes them from it).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = os.path.join(ROOT, "firmware-n6", "src", "application", "translator", "models.json")
HEADER = os.path.join(ROOT, "firmware-n6", "src", "application", "translator", "xl_models.h")
ALIGN = 0x10000  # 64 KB: a NOR erase block


def num(v):
    return int(v, 0) if isinstance(v, str) else int(v)


def load():
    with open(MODELS, encoding="utf-8") as f:
        return json.load(f)


def check(m):
    problems = []
    nor0, nor1 = num(m["nor"]["start"]), num(m["nor"]["start"]) + num(m["nor"]["size"])
    regions = sorted(m["flash"], key=lambda r: num(r["address"]))
    for r in regions:
        a, size = num(r["address"]), num(r["slot"])
        if a % ALIGN:
            problems.append("%s: address 0x%08X is not 64 KB aligned" % (r["name"], a))
        if a < nor0 or a + size > nor1:
            problems.append("%s: slot 0x%08X-0x%08X is outside the NOR" % (r["name"], a, a + size))
        path = os.path.join(ROOT, r["file"]) if r.get("file") else None
        r["_size"] = os.path.getsize(path) if path and os.path.exists(path) else None
        if r["_size"] is not None and r["_size"] > size:
            problems.append("%s: %s is %d bytes, larger than its slot (%d)" % (r["name"], r["file"], r["_size"], size))
    for p, q in zip(regions, regions[1:]):
        if num(p["address"]) + num(p["slot"]) > num(q["address"]):
            problems.append("%s overlaps %s" % (p["name"], q["name"]))
    ps0, ps1 = num(m["psram"]["start"]), num(m["psram"]["start"]) + num(m["psram"]["size"])
    for r in m["psram_regions"]:
        a, size = num(r["address"]), num(r["size"])
        if a < ps0 or a + size > ps1:
            problems.append("PSRAM %s: 0x%08X-0x%08X is outside the PSRAM" % (r["name"], a, a + size))
    return regions, problems


def show(m, regions):
    nor0 = num(m["nor"]["start"])
    end = nor0
    print("NOR flash (128 MB):")
    for r in regions:
        a, size = num(r["address"]), num(r["slot"])
        if a > end:
            print("  0x%08X  %6.2f MB  (free)" % (end, (a - end) / 1e6))
        used = "" if r["_size"] is None else "%6.2f MB used" % (r["_size"] / 1e6)
        print("  0x%08X  %6.2f MB  %-12s %s" % (a, size / 1e6, r["name"], used))
        end = a + size
    total = nor0 + num(m["nor"]["size"])
    if total > end:
        print("  0x%08X  %6.2f MB  (free)" % (end, (total - end) / 1e6))
    print("PSRAM (32 MB):")
    for r in sorted(m["psram_regions"], key=lambda r: num(r["address"])):
        print("  0x%08X  %6.2f MB  %-12s %s" % (num(r["address"]), num(r["size"]) / 1e6, r["name"], r.get("what", "")))


def write_header(m):
    lines = ["/**",
             " * @file     xl_models.h",
             " * @brief    Where the translator's models live: NOR flash slots and PSRAM regions.",
             " * @details  Generated by tools/models_layout.py from models.json; edit that file and rerun.",
             " *",
             " * SPDX-License-Identifier: Apache-2.0",
             " */",
             "#ifndef APPLICATION_TRANSLATOR_XL_MODELS_H",
             "#define APPLICATION_TRANSLATOR_XL_MODELS_H",
             ""]
    for r in m["flash"]:
        if r.get("macro"):
            lines.append("/** @brief %s */" % r["what"])
            lines.append("#define XL_MODEL_%s_ADDR 0x%08XU" % (r["macro"], num(r["address"])))
            lines.append("#define XL_MODEL_%s_SLOT 0x%08XU" % (r["macro"], num(r["slot"])))
            lines.append("")
    for r in m["psram_regions"]:
        if r.get("macro"):
            lines.append("/** @brief %s */" % r["what"])
            lines.append("#define XL_PSRAM_%s_ADDR 0x%08XU" % (r["macro"], num(r["address"])))
            lines.append("#define XL_PSRAM_%s_SIZE 0x%08XU" % (r["macro"], num(r["size"])))
            lines.append("")
    lines.append("#endif /* APPLICATION_TRANSLATOR_XL_MODELS_H */")
    text = "\n".join(lines) + "\n"
    old = open(HEADER, encoding="utf-8").read() if os.path.exists(HEADER) else None
    if old != text:
        with open(HEADER, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(HEADER, ROOT))


def main():
    m = load()
    regions, problems = check(m)
    show(m, regions)
    for p in problems:
        print("PROBLEM:", p)
    if "--check" not in sys.argv:
        write_header(m)
    sys.exit(1 if problems else 0)


if __name__ == "__main__":
    main()
