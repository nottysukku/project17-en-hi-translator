"""Write edu_math_tables.h, the word tables of the C checker, from the Python one (mathspeech.py).

The C parser (edu_math.c) is table-driven: every known word, misspelling and fuzzy-match target comes
from here, so adding an alias in mathspeech.py and re-running this script keeps the board in step.

  python gen_edu_tables.py [--mathspeech PATH] [--out PATH] [--check]

--check exits 1 when the header is missing or was made from a different mathspeech.py.
"""
import argparse
import hashlib
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
EDU = os.path.dirname(HERE)
# stm32n6-speech-recognition/src/application/edu/tools -> N6_AutoSpeech/ASR_Math_Game
DEFAULT_MATHSPEECH = os.path.normpath(os.path.join(EDU, *[".."] * 6, "ASR_Math_Game", "mathspeech.py"))

# Word classes; the order is the C enum edu_word_class_t.
CLASSES = ["UNIT", "TEEN", "TENS", "HUNDRED", "OP", "EQ", "FILLER", "FIX", "A", "OH", "BY"]
MEANING_OP, MEANING_EQ = 0xFE, 0xFF


def load(path):
    spec = importlib.util.spec_from_file_location("mathspeech", path)
    ms = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(ms)
    return ms


def sha1(path):
    return hashlib.sha1(open(path, "rb").read()).hexdigest()


def word_class(ms, lex, word):
    base = ms.PLURALS.get(word, word)
    found = []
    if base in ms.UNITS:
        found.append(("UNIT", ms.UNITS[base]))
    if base in ms.TEENS:
        found.append(("TEEN", ms.TEENS[base]))
    if base in ms.TENS:
        found.append(("TENS", ms.TENS[base]))
    if base == "HUNDRED":
        found.append(("HUNDRED", 100))
    if word in lex.operators:
        found.append(("OP", 0))
    if word in lex.equals:
        found.append(("EQ", 0))
    if word in ms.FILLERS:
        found.append(("FILLER", 0))
    if word in ms.CORRECTIONS:
        found.append(("FIX", 0))
    if word == "A":
        found.append(("A", 1))
    if word in ("OH", "O"):
        found.append(("OH", 0))
    if word == "BY":
        found.append(("BY", 0))
    assert len(found) == 1, (word, found)  # tokenize() relies on every word having one class
    return found[0]


def generate(ms, source_sha):
    lex = ms.DEFAULT_LEXICON
    known = sorted(set(lex.exact) | ms.FILLERS | ms.CORRECTIONS | {"A", "OH", "O", "BY"})
    index = {w: i for i, w in enumerate(known)}
    assert len(known) < MEANING_OP

    rows = []
    for w in known:
        cls, value = word_class(ms, lex, w)
        plural = 1 if w in ms.PLURALS else 0
        meaning = lex._meaning(w)
        meaning = {"op": MEANING_OP, "eq": MEANING_EQ}.get(meaning, index.get(meaning))
        assert meaning is not None, w
        rows.append((w, cls, value, plural, meaning))

    aliases = sorted((k, v) for k, v in ms.ALIASES.items() if k not in index)
    for k, v in aliases:
        assert lex.canonical(k) == v and v in index, (k, v)

    targets = list(lex.fuzzy_targets)  # already sorted, the order lookup() walks them in
    assert targets == sorted(targets)
    max_target = max(len(t) for t in targets)
    max_known = max(len(w) for w in known)
    max_alias = max(len(k) for k, _ in aliases)
    # Longest string that can match anything: a known word, an alias, or a fuzzy match (two edits).
    max_match = max(max_known, max_alias, max_target + 2)
    width = max(max_known, max_alias) + 1

    # Defaults the C code hard-codes; fail loudly if Python changes them.
    assert ms.STYLE_PENALTY == {"std": 0, "colloq": 2, "digits": 5}, ms.STYLE_PENALTY
    r = ms.Ranges()
    assert (r.table_min, r.table_max, r.mult_min, r.mult_max) == (2, 30, 1, 15)

    out = []
    out.append("/**")
    out.append(" * @file     edu_math_tables.h")
    out.append(" * @brief    Word tables of the spoken-multiplication checker (edu_math.c).")
    out.append(" * @details  GENERATED by tools/gen_edu_tables.py from ASR_Math_Game/mathspeech.py;")
    out.append(" *           do not edit. Re-run the script after changing the Python word lists.")
    out.append(" *")
    out.append(" * SPDX-License-Identifier: Apache-2.0")
    out.append(" */")
    out.append("#ifndef APPLICATION_EDU_EDU_MATH_TABLES_H")
    out.append("#define APPLICATION_EDU_EDU_MATH_TABLES_H")
    out.append("")
    out.append("#include <stdint.h>")
    out.append("")
    out.append('/** @brief SHA-1 of the mathspeech.py these tables were made from. */')
    out.append('#define EDU_MATH_TABLES_SOURCE_SHA1 "%s"' % source_sha)
    out.append("")
    out.append("/** @brief Bytes of one table word, terminator included. */")
    out.append("#define EDU_WORD_WIDTH %dU" % width)
    out.append("/** @brief Longest string that can match a word (known, alias, or fuzzy within two edits). */")
    out.append("#define EDU_MAX_MATCH_LEN %dU" % max_match)
    out.append("/** @brief Number of known words. */")
    out.append("#define EDU_KNOWN_COUNT %dU" % len(known))
    out.append("/** @brief Number of misspellings. */")
    out.append("#define EDU_ALIAS_COUNT %dU" % len(aliases))
    out.append("/** @brief Number of fuzzy-match targets. */")
    out.append("#define EDU_TARGET_COUNT %dU" % len(targets))
    out.append("/** @brief edu_known_t.meaning of an operator / an equals word. */")
    out.append("#define EDU_MEANING_OP 0x%02XU" % MEANING_OP)
    out.append("#define EDU_MEANING_EQ 0x%02XU" % MEANING_EQ)
    out.append("")
    out.append("/** @brief Class of a known word; decides its token kind. */")
    out.append("typedef enum")
    out.append("{")
    for c in CLASSES:
        out.append("    EDU_CLASS_%s," % c)
    out.append("} edu_word_class_t;")
    out.append("")
    out.append("/** @brief One known word. */")
    out.append("typedef struct")
    out.append("{")
    out.append("    uint8_t cls;     /**< edu_word_class_t. */")
    out.append("    uint8_t value;   /**< Number value (A: 1, HUNDRED: 100), else 0. */")
    out.append("    uint8_t plural;  /**< 1 for TWOS, SIXES, TWENTIES, ... */")
    out.append("    uint8_t meaning; /**< Singular word index, or EDU_MEANING_OP / EDU_MEANING_EQ. */")
    out.append("} edu_known_t;")
    out.append("")
    out.append("/** @brief Known words in strcmp order (exact words, fillers, corrections, A, OH, O, BY). */")
    out.append("static const char edu_known_words[EDU_KNOWN_COUNT][EDU_WORD_WIDTH] = {")
    for i in range(0, len(known), 6):
        out.append("    " + " ".join('"%s",' % w for w in known[i:i + 6]))
    out.append("};")
    out.append("")
    out.append("/** @brief Attributes of edu_known_words[i]. */")
    out.append("static const edu_known_t edu_known[EDU_KNOWN_COUNT] = {")
    for i, (w, cls, value, plural, meaning) in enumerate(rows):
        out.append("    { EDU_CLASS_%-7s %3d, %d, %3d }, /* %3d %s */" % (cls + ",", value, plural, meaning, i, w))
    out.append("};")
    out.append("")
    out.append("/** @brief Misspellings in strcmp order ... */")
    out.append("static const char edu_alias_words[EDU_ALIAS_COUNT][EDU_WORD_WIDTH] = {")
    for i in range(0, len(aliases), 6):
        out.append("    " + " ".join('"%s",' % k for k, _ in aliases[i:i + 6]))
    out.append("};")
    out.append("")
    out.append("/** @brief ... and the known word each one stands for. */")
    out.append("static const uint8_t edu_alias_target[EDU_ALIAS_COUNT] = {")
    for i in range(0, len(aliases), 12):
        out.append("    " + " ".join("%3d," % index[v] for _, v in aliases[i:i + 12]))
    out.append("};")
    out.append("")
    out.append("/** @brief Fuzzy-match targets (known words of three letters or more) in sorted order. */")
    out.append("static const uint8_t edu_targets[EDU_TARGET_COUNT] = {")
    for i in range(0, len(targets), 12):
        out.append("    " + " ".join("%3d," % index[t] for t in targets[i:i + 12]))
    out.append("};")
    out.append("")
    out.append("#endif /* APPLICATION_EDU_EDU_MATH_TABLES_H */")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--mathspeech", default=DEFAULT_MATHSPEECH)
    ap.add_argument("--out", default=os.path.join(EDU, "edu_math_tables.h"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    src = sha1(args.mathspeech)
    text = generate(load(args.mathspeech), src)
    if args.check:
        current = open(args.out, encoding="utf-8").read() if os.path.exists(args.out) else ""
        if current != text:
            print("%s is out of date with %s: run gen_edu_tables.py" % (args.out, args.mathspeech))
            sys.exit(1)
        print("tables up to date (mathspeech.py sha1 %s)" % src[:12])
        return
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s from %s (sha1 %s)" % (args.out, args.mathspeech, src[:12]))


if __name__ == "__main__":
    main()
